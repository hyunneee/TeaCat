-- ================================
-- 공연 비공개 표시를 deleted_at 에서 hidden_at 으로 분리
-- ================================
--
-- deleted_at 은 이름과 달리 "삭제"가 아니라 "비공개(API-271)" 표시로만 쓰이고 있었다.
-- 공연 삭제(API-263)는 행을 실제로 지우는 하드 삭제라 deleted_at 이 세팅되는 경로가 없다.
--
-- 이름이 의미와 다르면 나중에 소프트 삭제를 도입할 때 비공개와 삭제를 한 컬럼으로 구분할 수 없게 된다.
-- 그래서 실제 의미대로 hidden_at 으로 바꾼다. 값은 그대로 옮겨진다(비공개였던 공연은 비공개로 남는다).
-- 소프트 삭제가 필요해지면 그때 deleted_at 을 새 의미로 다시 추가한다.

ALTER TABLE performance_general
    RENAME COLUMN deleted_at TO hidden_at;
