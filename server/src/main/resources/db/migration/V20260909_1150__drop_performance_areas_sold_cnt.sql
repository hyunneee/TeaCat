-- ================================
-- performance_areas.sold_cnt 제거
-- ================================
-- 이 컬럼은 값을 갱신하는 코드가 없어 항상 0 이었다. 그래서 이 값을 보던 관리자 보호장치
-- 두 가지가 통과만 하고 있었다 —
--   ① 이미 판 수량보다 낮게 max_cnt 를 낮추는 것을 막는 검사
--   ② 판매 이력이 있는 구역을 삭제하는 것을 막는 검사
-- 티켓이 실제로 만들어지기 시작하면서 잠재적 문제가 실제 문제가 됐다.
--
-- 카운터를 채우는 대신 없앤다. 세 가지 이유다.
--   - 쓰는 곳(위 두 검사)은 관리자 화면뿐이라 그때그때 세도 부담이 없다
--   - 좌석 구역의 정원은 performance_seats 가 회차별로 이미 통제한다
--   - 스탠딩 정원 통제에는 못 쓴다. 이 테이블은 (공연, 구역) 단위라 회차 구분이 없어서,
--     회차마다 파는 수량을 담을 수 없다. 스탠딩을 붙일 때는 회차 단위 테이블이 따로 필요하다
--
-- 판매량의 진실은 tickets 다. 필요할 때 센다.
--
-- max_cnt 는 남긴다. 지금은 안내값이지만 스탠딩 정원의 근거가 될 값이다.

ALTER TABLE performance_areas
    DROP CONSTRAINT chk_performance_areas_sold_cnt,
    DROP COLUMN sold_cnt;
