-- ================================
-- 입장(검표) 기록
-- ================================
-- 게이트에서 QR 을 찍고 얼굴이 맞으면 이 시각을 남긴다.
--
-- 🔴 ticket_status 에 값을 더하지 않고 **컬럼을 따로 둔다.** 둘은 다른 축이다 —
--    예매 상태(CONFIRMED/CANCELLED)는 "표가 유효한가", 입장은 "그 표로 들어왔는가" 다.
--    한 컬럼에 섞으면 "입장했는데 취소된 표" 를 표현할 수 없고, PostgreSQL 은
--    ALTER TYPE ... ADD VALUE 를 같은 트랜잭션에서 쓸 수 없어 마이그레이션도 둘로 쪼개야 한다.
--
-- ⚠️ 이 값이 있으면 **다시 들어올 수 없다.** 같은 QR 로 두 명이 입장하는 것을 막는 것이
--    암표 방지의 마지막 고리다. 재입장(잠깐 나갔다 오기)이 필요해지면 정책을 먼저 정할 것 —
--    컬럼을 지우지 말고 "퇴장" 을 따로 두는 쪽이 기록이 남는다.

ALTER TABLE tickets ADD COLUMN checked_in_at timestamp;

COMMENT ON COLUMN tickets.checked_in_at IS '입장 확인 시각. NULL 이면 아직 입장하지 않음';
