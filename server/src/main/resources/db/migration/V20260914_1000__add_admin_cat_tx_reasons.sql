-- ================================
-- 캣머니 원장에 "관리자 조정" 사유를 추가한다
-- ================================
-- 관리자가 테스트용으로 특정 회원의 캣머니를 넣거나 빼는 기능(어드민 > 회원 관리)이
-- 생겼다. 기존 사유를 재사용하지 않는 이유는 원장이 거짓말을 하기 때문이다 —
-- REWARD 로 적으면 나중에 "이벤트로 얼마 나갔나" 를 셀 때 테스트 금액이 섞이고,
-- WITHDRAWAL 로 적으면 있지도 않은 원화 출금이 장부에 남는다.
--
-- 🔴 이 두 사유는 **대사(reconciliation) 대상이 아니다.** 실제 원화가 오간 적이
--    없으므로 원화 장부와 맞춰보면 반드시 어긋난다. 집계할 때 빼야 한다.

-- ────────────────────────────────────────────────────────────
-- 🔴 이 파일은 값만 추가하고 끝낸다. CHECK 는 다음 마이그레이션이 건다.
-- ────────────────────────────────────────────────────────────
-- PostgreSQL 12+ 는 ALTER TYPE ... ADD VALUE 를 트랜잭션 안에서 실행할 수는 있지만,
-- **같은 트랜잭션 안에서 그 값을 쓰지는 못한다** (unsafe use of new value ...).
-- CHECK 제약에 'ADMIN_GRANT' 를 적는 순간 그 값을 쓰는 것이라, 한 파일에 합치면
-- 마이그레이션이 실패한다. Flyway 는 마이그레이션마다 트랜잭션을 따로 잡으므로
-- (group = false 가 기본) 파일을 나누면 커밋 경계가 생겨 해결된다.
--
-- 되돌릴 수 없다 — enum 값은 DROP 이 없다. 그래서 추가 자체는 멱등으로 둔다.

ALTER TYPE cat_tx_reason ADD VALUE IF NOT EXISTS 'ADMIN_GRANT';
ALTER TYPE cat_tx_reason ADD VALUE IF NOT EXISTS 'ADMIN_BURN';
