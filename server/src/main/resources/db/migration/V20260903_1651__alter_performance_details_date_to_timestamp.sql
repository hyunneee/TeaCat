-- ================================
-- 회차의 공연 일자를 "일시"로 바꾼다
-- ================================
--
-- API-265 명세는 "회차 번호·공연 일시" 를 받는다고 정의하지만
-- V1 은 performance_date 를 date 로 잡아 시각이 잘려 있었다.
--
-- 시각이 없으면 이런 것들이 불가능하다.
--   - 취소 마감을 "공연 시작 전까지" 로 계산 (API-205)
--   - 같은 날 낮/밤 공연을 구분 (2회차 이상 운영)
--
-- 이름은 ERD·문서와 맞추기 위해 그대로 둔다. date -> timestamp 변환은
-- 기존 값을 그 날 00:00 으로 채우므로 데이터 손실이 없다.

ALTER TABLE performance_details
    ALTER COLUMN performance_date TYPE timestamp;
