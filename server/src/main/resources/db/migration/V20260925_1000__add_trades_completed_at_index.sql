-- 이상거래 심사가 보는 "최근 기간" 조회에 쓸 인덱스 (AUCTION_FRAUD_DESIGN.md 14-2-2 · 14-2-3).
--
-- 심사는 거래 한 건마다 맥락을 모으는데, 그중 둘이 completed_at 으로 기간을 자른다.
--   · 그래프 — 최근 7일 거래로 만든 판매자→구매자 망에서 최단 경로 (재귀 CTE)
--   · 속도   — 최근 10분·1시간·24시간의 거래 빈도
-- 둘 다 쓸 인덱스가 없어 Seq Scan 이었다. 완료 거래 14,886건 기준 9.1ms + 4.4ms 로,
-- 거래 1건 정산에 붙는 ~16ms 의 대부분이 이 둘이었다.
--
-- 🔴 지금 당장 빨라지지는 않는다. 운영 완료 거래가 73건이라 전체를 훑어도 순식간이고,
--    기간 조건이 전체의 절반을 넘으면 옵티마이저가 Seq Scan 을 고르는 것이 맞다.
--    이 인덱스가 일하는 시점은 **과거가 쌓여 최근 기간이 전체의 일부가 될 때**다.
--    그때는 거래량에 비례해 느려지는데, 하필 도는 자리가 정산 트랜잭션 안이고
--    경매 마감이 몰리는 시각과 겹친다 — 느려진 뒤에 원인을 찾는 것보다 미리 두는 편이 싸다.
--
-- 부분 인덱스인 이유: 심사가 보는 것은 언제나 완료된 거래뿐이다(보류·실패·보상된 거래는
-- 시장 가격도 거래망도 아니다). 조건을 걸면 색인 대상이 줄고 쓰기 비용도 그만큼 적다.

CREATE INDEX idx_nft_photocard_trades_completed_at
    ON nft_photocard_trades (completed_at)
    WHERE chain_status = 'COMPLETED';
