-- ================================
-- 같이 하는 게임(윷놀이·할리갈리)이 쓸 원장 사유를 추가한다
-- ================================
-- 판돈을 잃는 것은 티켓 결제(PAYMENT)가 아니고, 상금을 받는 것은 출석 보상(REWARD)이
-- 아니다. 기존 사유를 재사용하면 원장이 거짓말을 한다 —
--   · PAYMENT 로 적으면 있지도 않은 티켓 매출이 잡히고,
--   · REWARD 로 적으면 "이벤트로 우리가 푼 돈" 에 남이 낸 판돈이 섞인다.
-- 게임에서 실제로 새로 생기는 돈은 판마다 얹어주는 보조금(인원수 × 정액)뿐이다.
--
-- ────────────────────────────────────────────────────────────
-- 🔴 이 파일은 값만 추가하고 끝낸다. CHECK 와 테이블은 다음 마이그레이션이 만든다.
-- ────────────────────────────────────────────────────────────
-- PostgreSQL 12+ 는 ALTER TYPE ... ADD VALUE 를 트랜잭션 안에서 실행할 수는 있지만,
-- **같은 트랜잭션 안에서 그 값을 쓰지는 못한다** (unsafe use of new value ...).
-- CHECK 제약에 'GAME_BET' 을 적는 순간 그 값을 쓰는 것이라, 한 파일에 합치면
-- 마이그레이션이 실패한다 (V20260914_1000 에서 같은 이유로 파일을 나눴다).
--
-- 되돌릴 수 없다 — enum 값은 DROP 이 없다. 그래서 추가 자체는 멱등으로 둔다.

ALTER TYPE cat_tx_reason ADD VALUE IF NOT EXISTS 'GAME_PRIZE';
ALTER TYPE cat_tx_reason ADD VALUE IF NOT EXISTS 'GAME_BET';

-- 방에 들어온 순간부터 판돈은 가용 잔액에서 빠져 있어야 한다. 게임 중에 그 돈을 다른 데
-- 써버리면 정산할 돈이 없다. ref_id = game_participants.id
ALTER TYPE cat_money_hold_ref_type ADD VALUE IF NOT EXISTS 'GAME_BET';
