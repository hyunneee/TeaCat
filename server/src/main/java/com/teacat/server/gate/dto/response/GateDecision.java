package com.teacat.server.gate.dto.response;

/**
 * 검표 판정 — 통과 / 보류 / 거절.
 *
 * <p><b>왜 둘이 아니라 셋인가.</b> 통과·거절만 두면 경계값 하나가 모든 걸 결정한다. 그런데
 * 같은 사람도 조명·각도에 따라 점수가 흩어져서, 경계를 높이면 본인이 거절당하고 낮추면 남이
 * 통과한다. 어느 쪽으로 옮겨도 한쪽이 나빠진다.
 *
 * <p>애매한 구간은 <b>기계가 정하지 않고 사람에게 넘긴다.</b> 운영자가 화면의 좌석·이름을 보고
 * 눈앞의 사람과 맞춰 본 뒤 통과 버튼을 누른다. 입구에 사람이 이미 서 있는데 그 판단을
 * 안 쓸 이유가 없다.
 */
public enum GateDecision {

    /** 들여보낸다. 이 응답이 나갈 때 입장 기록이 이미 만들어져 있다 */
    MATCH,

    /**
     * 운영자가 육안으로 확인한다.
     *
     * <p>점수는 충분한데 2등과의 간격이 좁은 경우도 여기로 온다 — 누구인지 모르는 상태라
     * 1등을 그냥 통과시킬 수 없다.
     */
    REVIEW,

    /** 다시 찍는다. 후보가 아예 없을 때도 이 값이다 */
    NO_MATCH
}
