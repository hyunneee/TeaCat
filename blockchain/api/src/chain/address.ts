import { getAddress } from 'ethers';

/**
 * 주소를 검증하고 소문자로 정규화합니다. (DESIGN.md 4-7)
 *
 * ── 정규식만으로는 부족합니다 ─────────────────────────────────────
 * 컨트롤러의 `^0x[0-9a-fA-F]{40}$` 는 **모양만** 봅니다. 이더리움 주소는 EIP-55
 * 체크섬을 대소문자로 인코딩하는데, 대소문자가 섞였는데 체크섬이 안 맞는 주소를
 * ethers 에 넘기면 거기서 `INVALID_ARGUMENT` 를 던집니다. `AppError` 가 아니라서
 * **500 으로 떨어집니다** — 실제로 Swagger 가 정규식만 보고 만들어낸 예시 주소로
 * 밟았습니다.
 *
 * 여기서 걸러 400 으로 내려줍니다. 잘못된 건 클라이언트 입력이지 서버가 아닙니다.
 *
 * ── 왜 소문자로 낮추는가 ─────────────────────────────────────────
 * 체크섬 검사를 통과한 뒤에는 소문자가 정본입니다. 대소문자가 섞인 채로 저장하면
 * 같은 주소가 두 값이 되어 비교와 UNIQUE 제약이 무력해집니다. (4-7)
 *
 * 전부 소문자·전부 대문자인 주소는 "체크섬 없음" 으로 간주되어 통과합니다.
 * 섞인 경우에만 검사합니다 — EIP-55 의 규칙이 그렇습니다.
 */
export function normalizeAddress(value: string): string | null {
  try {
    return getAddress(value).toLowerCase();
  } catch {
    return null;
  }
}
