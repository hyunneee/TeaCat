import { Outlet } from 'react-router-dom';
import { useScrollTop } from '@/shared/hooks';

/**
 * 라우트가 바뀔 때 공통으로 해야 하는 일을 모아두는 자리.
 * 지금은 **스크롤 위치 정리** 하나뿐입니다.
 *
 * ── 왜 등장 애니메이션이 없나 (원래 페이드가 있었습니다) ──
 * 새 화면을 `opacity: 0 → 1` 로 띄우면, 그 0.24초 동안 화면에 보이는 건
 * **앱의 흰 바탕**입니다. 홈·마이페이지처럼 위쪽이 짙은 화면으로 넘어갈 때
 * 이게 **흰 화면이 한 번 깜빡이는 것**으로 보입니다 (특히 휴대폰에서 눈에 띕니다).
 * 화면 전환은 티켓팅에서 얻는 것보다 잃는 게 큰 연출이라 걷어냈습니다.
 * 지금은 이전 화면에서 새 화면으로 **즉시** 바뀝니다.
 *
 * ⚠️ 다시 넣고 싶다면 `opacity` 가 아니라 **화면 안 요소**(`Stagger`)에 넣으세요.
 *    화면 전체를 투명하게 만드는 연출은 배경색을 그대로 노출시킵니다.
 * ⚠️ `AnimatePresence`(교차 전환)도 쓰지 마세요 — exit 이 끝나지 않으면
 *    네비게이션이 그대로 멈춥니다. (DESIGN.md 3장)
 */
export function PageTransition() {
  /* 탭을 옮기면 맨 위에서 시작합니다 (뒤로가기는 제외 — useScrollTop 주석 참고) */
  useScrollTop();

  return <Outlet />;
}
