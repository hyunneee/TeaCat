/**
 * 캣머니 잔액.
 *
 * 서버가 체인에서 바로 읽어 내려줍니다. 어디에도 저장되지 않으므로
 * 결제·구매 직후에는 `tokenKeys.balance()` 를 무효화해서 다시 받아야 합니다.
 *
 * 🔴 **화면의 "잔액" 자리에는 언제나 `available` 을 넣습니다.**
 * 5만을 가진 사람이 4만을 경매에 입찰하면 지금 쓸 수 있는 돈은 1만입니다.
 * `balance`(체인 총액)를 잔액으로 띄우면 두 가지가 깨집니다.
 *   1. 돈이 있어 보이는데 결제가 거절됩니다 — 사용자는 버그로 신고합니다.
 *   2. 낙찰되어 4만이 실제로 나가는 순간 5만 → 1만으로 뚝 떨어집니다.
 * `available` 로 두면 입찰한 순간 이미 빠져 있어 낙찰 때 화면이 흔들리지 않습니다.
 * (server 설계 8-3 · specs/2026-09-08-nft-auction-frontend-design.md 8장)
 *
 * ⚠️ 화면에 보이는 이 숫자는 **표시용**입니다.
 * 결제·구매에서 실제로 얼마가 빠질지는 **서버가 확정**합니다.
 * 프론트가 계산한 값을 결제 요청에 실어 보내면 공짜 티켓이 나옵니다.
 * (CLAUDE.md 7장 · DESIGN.md 12장)
 */
export interface TokenBalance {
  /** 체인에 있는 총액. 캣머니는 소수가 없어 정수입니다 */
  balance: number;
  /** 경매 입찰 등으로 묶여 있어 지금 쓸 수 없는 금액 */
  held: number;
  /** 지금 쓸 수 있는 금액 (`balance − held`, 음수면 0). **화면의 잔액은 이 값입니다** */
  available: number;
  /** 표기 단위 (지금은 항상 CAT) */
  symbol: string;
}
